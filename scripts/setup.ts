import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PASSWORD_LENGTH = 24;
const SECRET_BYTES = 24;
const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

export function fillEnv(
  existing: string | null,
  opts?: { force?: boolean; random?: (n: number) => Buffer },
): { text: string; password: string | null; changed: boolean } {
  const random = opts?.random ?? randomBytes;
  const force = opts?.force ?? false;
  const password = { value: null as string | null };
  const secret = { value: null as string | null };

  const generatedPassword = (): string => {
    if (password.value === null) password.value = generatePassword(random);
    return password.value;
  };
  const generatedSecret = (): string => {
    if (secret.value === null) secret.value = generateSecret(random);
    return secret.value;
  };

  if (existing === null) {
    const text = [
      "# Friendform configuration. Generated by bun run setup.",
      "# NODE_ENV=development",
      "# HOST=127.0.0.1",
      "# PORT=3000",
      "# PUBLIC_URL=",
      "# DATA_DIR=./data",
      "# DATABASE_URL=",
      `ADMIN_PASSWORD=${generatedPassword()}`,
      `SESSION_SECRET=${generatedSecret()}`,
      "# TRUST_PROXY=",
      "# WEBHOOK_SECRET=",
      "# AI_BASE_URL=",
      "# AI_API_KEY=",
      "# AI_MODEL=",
      "",
    ].join("\n");
    return { text, password: password.value, changed: true };
  }

  const newline = existing.includes("\r\n") ? "\r\n" : "\n";
  const endsWithNewline = existing.endsWith("\n");
  const lines = existing.split(/\r?\n/);
  if (endsWithNewline && lines[lines.length - 1] === "") lines.pop();

  let sawPassword = false;
  let sawSecret = false;
  const nextLines = lines.map((line) => {
    if (/^\s*#/.test(line)) return line;
    const match = /^(\s*)(ADMIN_PASSWORD|SESSION_SECRET)(\s*=\s*)(.*)$/.exec(line);
    if (!match) return line;
    const key = match[2];
    const rawValue = match[4] ?? "";
    if (key === "ADMIN_PASSWORD") sawPassword = true;
    if (key === "SESSION_SECRET") sawSecret = true;
    if (!force && !isBlank(rawValue)) return line;
    const value = key === "ADMIN_PASSWORD" ? generatedPassword() : generatedSecret();
    return `${match[1] ?? ""}${key ?? ""}${match[3] ?? "="}${value}`;
  });

  if (!sawPassword) nextLines.push(`ADMIN_PASSWORD=${generatedPassword()}`);
  if (!sawSecret) nextLines.push(`SESSION_SECRET=${generatedSecret()}`);

  let text = nextLines.join(newline);
  if ((endsWithNewline || !sawPassword || !sawSecret) && !text.endsWith("\n")) text += newline;
  if (endsWithNewline && !text.endsWith(newline)) text += newline;
  return { text, password: password.value, changed: text !== existing };
}

function isBlank(raw: string): boolean {
  const trimmed = raw.trim();
  if (trimmed === "") return true;
  const quoted =
    (trimmed.startsWith('"') && trimmed.endsWith('"') && trimmed.length >= 2) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'") && trimmed.length >= 2);
  return quoted && trimmed.slice(1, -1).trim() === "";
}

function generatePassword(random: (n: number) => Buffer): string {
  let out = "";
  while (out.length < PASSWORD_LENGTH) {
    const bytes = random(PASSWORD_LENGTH);
    if (bytes.length === 0) throw new Error("random returned no bytes");
    for (const byte of bytes) {
      if (byte >= 248) continue;
      const char = ALPHABET[byte % ALPHABET.length];
      if (char === undefined) continue;
      out += char;
      if (out.length === PASSWORD_LENGTH) break;
    }
  }
  return out;
}

function generateSecret(random: (n: number) => Buffer): string {
  const bytes = Buffer.alloc(SECRET_BYTES);
  let filled = 0;
  while (filled < SECRET_BYTES) {
    const chunk = random(SECRET_BYTES - filled);
    if (chunk.length === 0) throw new Error("random returned no bytes");
    const copy = Math.min(chunk.length, SECRET_BYTES - filled);
    chunk.copy(bytes, filled, 0, copy);
    filled += copy;
  }
  return bytes.toString("hex");
}

function main(): void {
  const args = new Set(process.argv.slice(2));
  const ensure = args.has("--ensure");
  const force = args.has("--force");
  const envPath = path.resolve(process.cwd(), ".env");
  const existing = existsSync(envPath) ? readFileSync(envPath, "utf8") : null;
  const result = fillEnv(existing, { force });
  if (existing === null || result.changed) {
    writeFileSync(envPath, result.text, { encoding: "utf8", mode: 0o600 });
  }
  if (existsSync(envPath)) chmodSync(envPath, 0o600);
  if (result.password) {
    process.stdout.write(`Owner password: ${result.password} (saved in .env)\n`);
  } else if (!ensure && !result.changed) {
    process.stdout.write("Your .env already has an owner password and a session secret.\n");
  }
}

const thisFile = fileURLToPath(import.meta.url);
const invoked = process.argv.some((arg) => path.resolve(arg) === thisFile);
if (invoked) main();
